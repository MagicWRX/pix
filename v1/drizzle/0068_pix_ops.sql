-- md5 over the ordered primary-key values of one table: a checksum a
-- row count cannot fake. Raises if the table has no primary key.
CREATE OR REPLACE FUNCTION pix_ops.table_checksum(p_schema text, p_table text)
RETURNS text
LANGUAGE plpgsql STABLE AS $$
DECLARE
  pk_expr text;
  result  text;
BEGIN
  SELECT '(' || string_agg(quote_ident(a.attname), ', ' ORDER BY array_position(i.indkey, a.attnum)) || ')::text'
    INTO pk_expr
    FROM pg_class c
    JOIN pg_index i ON i.indrelid = c.oid AND i.indisprimary
    JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum = ANY (i.indkey)
   WHERE c.relnamespace = p_schema::regnamespace AND c.relname = p_table;
  IF pk_expr IS NULL THEN
    RAISE EXCEPTION 'table_checksum: no primary key on %.%', p_schema, p_table;
  END IF;
  EXECUTE format(
    'SELECT md5(coalesce(string_agg(pk_text, chr(10) ORDER BY pk_text), '''')) '
    'FROM (SELECT %s AS pk_text FROM %I.%I) s', pk_expr, p_schema, p_table)
    INTO result;
  RETURN result;
END $$;

-- {table_name: checksum} for every PK-bearing table in a schema — the
-- manifest stored on pix_ops.deployments at each deploy.
CREATE OR REPLACE FUNCTION pix_ops.checksum_manifest(p_schema text)
RETURNS jsonb
LANGUAGE plpgsql STABLE AS $$
DECLARE
  r      record;
  result jsonb := '{}'::jsonb;
BEGIN
  FOR r IN
    SELECT DISTINCT c.relname AS tbl
      FROM pg_class c JOIN pg_index i ON i.indrelid = c.oid AND i.indisprimary
     WHERE c.relnamespace = p_schema::regnamespace AND c.relkind = 'r'
     ORDER BY 1
  LOOP
    result := result || jsonb_build_object(r.tbl, pix_ops.table_checksum(p_schema, r.tbl));
  END LOOP;
  RETURN result;
END $$;

CREATE OR REPLACE FUNCTION pix_ops.row_count_max_updated(p_schema text, p_table text)
RETURNS jsonb
LANGUAGE plpgsql STABLE AS $$
DECLARE
  has_ua boolean;
  result jsonb;
BEGIN
  SELECT EXISTS (
    SELECT 1 FROM pg_attribute
     WHERE attrelid = (p_schema || '.' || p_table)::regclass
       AND attname = 'updated_at' AND NOT attisdropped)
    INTO has_ua;
  IF has_ua THEN
    EXECUTE format(
      'SELECT jsonb_build_object(''rows'', count(*), ''max_updated_at'', max(updated_at)) FROM %I.%I',
      p_schema, p_table) INTO result;
  ELSE
    EXECUTE format(
      'SELECT jsonb_build_object(''rows'', count(*), ''max_updated_at'', NULL) FROM %I.%I',
      p_schema, p_table) INTO result;
  END IF;
  RETURN result;
END $$;

