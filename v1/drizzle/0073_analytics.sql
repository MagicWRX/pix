CREATE SCHEMA IF NOT EXISTS analytics;

CREATE TABLE IF NOT EXISTS analytics.events (
  id              bigint GENERATED BY DEFAULT AS IDENTITY,
  occurred_at     timestamptz NOT NULL,
  build_sha12     text NOT NULL,
  surface         text,
  action          text,
  subject_hash    text NULL,
  props           jsonb,
  idempotency_key text,
  PRIMARY KEY (id, occurred_at),
  UNIQUE (idempotency_key, occurred_at)
) PARTITION BY RANGE (occurred_at);

-- Default partition so inserts never fail before Local stands up
-- monthly partitions operationally; the retention script covers it.
CREATE TABLE IF NOT EXISTS analytics.events_default
  PARTITION OF analytics.events DEFAULT;

CREATE INDEX IF NOT EXISTS idx_analytics_events_build
  ON analytics.events (build_sha12, occurred_at);

CREATE TABLE IF NOT EXISTS analytics.daily_builds (
  day         date NOT NULL,
  build_sha12 text NOT NULL,
  sessions    integer NOT NULL DEFAULT 0,
  events      integer NOT NULL DEFAULT 0,
  PRIMARY KEY (day, build_sha12)
);

